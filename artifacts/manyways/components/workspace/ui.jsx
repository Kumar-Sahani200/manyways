"use client";
import { useEffect, useRef } from "react";

export function Modal({ title, children, actions, onClose, danger }) {
  const ref = useRef(null);
  const closeRef = useRef(onClose);
  closeRef.current = onClose;
  useEffect(() => {
    const prev = document.activeElement;
    const el = ref.current;
    (el.querySelector("[data-autofocus]") || el.querySelector("button"))?.focus();
    const key = (e) => {
      if (e.key === "Escape") { e.stopPropagation(); closeRef.current(); }
      if (e.key === "Tab") {
        const f = [...el.querySelectorAll("button,input,textarea,select,[href]")].filter((x) => !x.disabled);
        if (!f.length) return;
        const first = f[0], last = f[f.length - 1];
        if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
        else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
      }
    };
    document.addEventListener("keydown", key);
    return () => { document.removeEventListener("keydown", key); prev?.focus?.(); };
  }, []);
  return (
    <div className="ws-scrim" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div ref={ref} className={`ws-modal ${danger ? "danger" : ""}`} role={danger ? "alertdialog" : "dialog"} aria-modal="true" aria-label={title}>
        <h3 className="serif" style={{ fontSize: 28 }}>{title}</h3>
        <div className="ws-modal-body">{children}</div>
        <div className="row" style={{ justifyContent: "flex-end" }}>{actions}</div>
      </div>
    </div>
  );
}

export function Skeleton({ rows = 3, h = 56 }) {
  return <div role="status" aria-label="Loading" style={{ display: "grid", gap: 10 }}>{Array.from({ length: rows }, (_, i) => <div key={i} className="skel" style={{ height: h }} />)}</div>;
}

